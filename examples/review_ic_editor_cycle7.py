"""Real PAINT clean/diagnostic E3 lead-end targets; all data SYNTHETIC.

An editor hotspot is not an electrical connection, physical package drawing
or a ГОСТ printer symbol. SHA/DPI evidence generated by joint CI.
"""
import argparse
import hashlib
import json
from dataclasses import replace
from pathlib import Path
from xml.etree import ElementTree as ET

from examples.review_ic_cycle7 import synthetic_ic
from gost_schematic.core.geometry import Box
from gost_schematic.core.units import format_mm
from gost_schematic.electrical.ic import IcGraphicProfile, IcKind, IcPinType, IcTextAngle
from gost_schematic.electrical.ic_editor_targets import (
    make_ic_editor_manifest,
    render_ic_editor_review,
    verify_ic_editor_manifest,
)
from gost_schematic.electrical.ic_graphic_revision import (
    revise_ic_text_orientation,
    validate_ic_graphic_revision,
)
from gost_schematic.electrical.ic_paint_bridge import (
    bind_ic_paint_text_only,
    propose_ic_paint_binding,
)
from gost_schematic.electrical.ic_serde import IcLibraryRecord
from gost_schematic.engines.annotation.metrics import PillowTextMeasurer
from gost_schematic.model.circuit import Circuit, ComponentInstance, Net, PinRef
from gost_schematic.standards.type_a_font import inspect_type_a_font


def _source(count: int, kind: IcKind) -> IcLibraryRecord:
    original = synthetic_ic(count, kind)
    pin_roles = {
        "2": (IcPinType.INPUT, "VCC_LABEL_ONLY_NO_NET"),
        "3": (IcPinType.BIDIRECTIONAL, "IO"),
        "4": (IcPinType.POWER_OUTPUT, "SUPPLY_OUTPUT"),
        str(count - 3): (IcPinType.PASSIVE, "COMMON"),
    }
    device = replace(original.device, pins=tuple(
        replace(pin, electrical_type=pin_roles[pin.number][0],
                name=pin_roles[pin.number][1])
        if pin.number in pin_roles else pin for pin in original.device.pins
    ))
    specs = tuple(replace(
        s, main_field="PWM_CONTROLLER",
        body=Box(0, 0, 60000, 300000),
        profile=IcGraphicProfile.experimental_portrait_pwm(),
    ) for s in original.specs)
    return IcLibraryRecord(device, specs, original.placements)


def _circuit(record: IcLibraryRecord) -> Circuit:
    ref = record.placements[0].component_ref
    number = record.device.package.pin_count
    return Circuit((ComponentInstance(ref, record.device.identifier),), (
        Net("SIGNAL_IO", (PinRef(ref, "3"),)),
        Net("POWER_SUPPLY", (PinRef(ref, str(number - 1)),)),
        Net("OC_DRAIN", (PinRef(ref, str(number - 2)),)),
    ))


def _rects(svg: str, layer_name: str) -> list[ET.Element]:
    root = ET.fromstring(svg)
    layers = [node for node in root.iter()
              if node.attrib.get("data-layer") == layer_name]
    if len(layers) != 1:
        raise ValueError("IC_EDITOR_EXPECTED_EXACTLY_ONE_LAYER")
    return list(layers[0])


def generate(output_dir: Path, font: Path) -> dict:
    style = inspect_type_a_font(font, h_um=3500).style
    measurer = PillowTextMeasurer()
    output_dir.mkdir(parents=True, exist_ok=True)
    result = {
        "status": "SYNTHETIC_DRAFT_EDITOR_ONLY_NOT_GOST_APPROVED",
        "font_sha256": style.font_sha256,
        "units": [],
    }
    for kind, count in (
        (IcKind.ANALOG, 8), (IcKind.DIGITAL, 14),
        (IcKind.DIGITAL, 40), (IcKind.DIGITAL, 64),
    ):
        original = _source(count, kind)
        binding90 = propose_ic_paint_binding(original, style, measurer)
        circuit = _circuit(binding90.record)
        new_record = revise_ic_text_orientation(
            binding90.record, IcTextAngle.HORIZONTAL,
        )
        assert not validate_ic_graphic_revision(
            binding90.record, new_record, circuit=circuit,
        ).moved
        binding0 = bind_ic_paint_text_only(binding90, new_record)
        before = circuit.nets
        for angle, binding in ((90, binding90), (0, binding0)):
            all_contacts = make_ic_editor_manifest(binding, circuit)
            verify_ic_editor_manifest(binding, all_contacts, circuit)
            clean = render_ic_editor_review(
                binding, style, measurer, circuit=circuit, diagnostics=False,
            )
            diag = render_ic_editor_review(
                binding, style, measurer, circuit=circuit, diagnostics=True,
            )
            for unit_id, view, clean_svg, diag_svg in zip(
                binding.unit_ids, binding.views, clean, diag, strict=True,
            ):
                real = all_contacts.for_unit(unit_id)
                rects = _rects(diag_svg.svg, "editor-connection-targets")
                if len(rects) != len(real):
                    raise ValueError("IC_EDITOR_INCOMPLETE_HOTSPOT_INK")
                if "editor-connection-targets" in clean_svg.svg:
                    raise ValueError("IC_EDITOR_PRINT_LAYER_LEAK")
                for original_svg in (clean_svg.svg, diag_svg.svg):
                    parsed = ET.fromstring(original_svg)
                    lead_layers = [
                        node for node in parsed.iter()
                        if node.attrib.get("data-layer")
                        == "ic-physical-pin-leads"
                    ]
                    if len(lead_layers) != 1:
                        raise ValueError("IC_EDITOR_REAL_LEAD_LAYER_MISSING")
                    lead_map = {
                        n.attrib["data-pin-number"]: n.attrib
                        for n in lead_layers[0] if n.tag.endswith("line")
                    }
                    if len(lead_map) != len(real):
                        raise ValueError("IC_EDITOR_REAL_PHYSICAL_LEAD_COVERAGE")
                    for contact in real:
                        line = lead_map[contact.physical_number]
                        if (
                            line.get("x2") != format_mm(contact.anchor.x)
                            or line.get("y2") != format_mm(contact.anchor.y)
                            or line.get("data-real-anchor") != "true"
                        ):
                            raise ValueError(
                                "IC_EDITOR_PHYSICAL_LEAD_1UM_MISMATCH"
                            )
                found = {node.attrib["data-pin-ref"]: node for node in rects}
                if len(found) != len(real):
                    raise ValueError("IC_EDITOR_DUPLICATE_XML_MARKER")
                for contact in real:
                    ref = f"{contact.pin_ref.reference}.{contact.physical_number}"
                    ink = found[ref].attrib
                    if (
                        ink["x"] != format_mm(contact.anchor.x - 350)
                        or ink["y"] != format_mm(contact.anchor.y - 350)
                        or ink["width"] != "0.7" or ink["height"] != "0.7"
                        or ink["data-connectable"] != str(contact.connectable).lower()
                        or ink["data-net-id"] != (contact.net_id or "")
                        or ink["data-reason"] != (contact.reason or "")
                    ):
                        raise ValueError("IC_EDITOR_XML_ENDPOINT_OR_SEMANTIC_MISMATCH")
                name = f"{kind.reference_prefix}{count}-{unit_id}-PWM{angle}"
                for suffix, svg in (("clean", clean_svg.svg),
                                    ("diagnostic", diag_svg.svg)):
                    (output_dir / f"{name}-{suffix}.svg").write_text(
                        svg, encoding="utf-8",
                    )
                result["units"].append({
                    "name": name,
                    "component_ref": view.reference.split(".")[0],
                    "unit_id": unit_id,
                    "angle": angle,
                    "body_um": [
                        view.body.min_x, view.body.min_y,
                        view.body.max_x, view.body.max_y,
                    ],
                    "pinrefs": [
                        {
                            "component_ref": c.component_ref,
                            "unit_id": c.unit_id,
                            "physical_number": c.physical_number,
                            "pin_ref": [c.pin_ref.reference, c.pin_ref.number],
                            "type": c.electrical_type.value,
                            "role": c.role,
                            "world_um": [c.anchor.x, c.anchor.y],
                            "net": c.net_id,
                            "connectable": c.connectable,
                            "reason": c.reason,
                        } for c in real
                    ],
                    "clean_svg": f"{name}-clean.svg",
                    "diagnostic_svg": f"{name}-diagnostic.svg",
                })
        if circuit.nets != before:
            raise ValueError("IC_EDITOR_RENDER_MUTATED_CIRCUIT_NET")
    evidence = json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    (output_dir / "physical-pinref-editor-manifest.json").write_text(
        evidence, encoding="utf-8",
    )
    print(json.dumps({
        "status": result["status"],
        "view_count": len(result["units"]),
        "contact_count": sum(len(u["pinrefs"]) for u in result["units"]),
        "manifest_sha256": hashlib.sha256(evidence.encode()).hexdigest(),
    }, sort_keys=True))
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-file", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    a = parser.parse_args()
    generate(a.output_dir, a.font_file)


if __name__ == "__main__":
    main()
