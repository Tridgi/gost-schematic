def demand(condition: bool, error: str) -> None:
    if not condition:
        raise AssertionError(error)


def validate_real_b_native_layer(
    root: ET.Element, b_anchor: dict, font_sha: str, mode: str,
) -> None:
    """Independently verify exact signed b source, not electrical pads."""
    # This ink is generated by the true typed source-continuation
    # composer. Its two b rings are not electrical junctions or pads.
    regions = root.findall(
        f".//{SVG}g[@data-layer='typed-nonphysical-continuations']"
    )
    demand(len(regions) == 1 and
           regions[0].get("data-nonphysical") == "true" and
           regions[0].get("data-do-not-infer-net-from-shapes") == "true",
           "QA_C13_NATIVE_SOURCE_B_LAYER_UNVERIFIED")
    circles = regions[0].findall(
        f"./{SVG}circle[@data-nonphysical-net-continuation]"
    )
    demand(len(circles) == 2 and
           {circle.get("data-nonphysical-net-continuation")
            for circle in circles} == set(b_anchor) and
           all(circle.get("data-electrical-junction") == "false" and
               circle.get("fill") == "#ffffff"
               for circle in circles),
           "QA_C13_B_MARKER_SPOOFED_AS_PHYSICAL_NET_JOIN")
    for circle in circles:
        ident = circle.get("data-nonphysical-net-continuation")
        expected_xy = b_anchor[ident]
        true_xy = [
            Decimal(circle.get("cx")) * 1000,
            Decimal(circle.get("cy")) * 1000,
        ]
        demand(true_xy == expected_xy,
               "QA_C13_REAL_SIGNED_B_SOURCE_UM_POSITION_DRIFT")
    b_labels = regions[0].findall(
        f"./{SVG}text[@data-source='typed-net-continuation-v2']"
    )
    demand(len(b_labels) == 2 and
           all(t.text == "b" and t.get("data-nonphysical") == "true" and
               t.get("data-font-sha256") == font_sha and
               t.get("font-family") == "OpenGOST type A"
               for t in b_labels),
           "QA_C13_B_TEXT_IS_NOT_GENUINE_SOURCE_TYPE_A_LABEL")
    b_editor = regions[0].findall(
        f"./{SVG}rect[@data-layer='nonphysical-continuation-editor-reading-zone']"
    )
    demand(len(b_editor) == (2 if mode == "diagnostic" else 0) and
           all(t.get("data-connectable") == "false" and
               t.get("data-not-a-physical-terminal") == "true"
               for t in b_editor),
           "QA_C13_B_LABEL_EDITOR_NOT_TRUE_NONPHYSICAL_POLICY")



def assess_source_b_stub_ink(
    root: ET.Element, b_witness: dict,
) -> str:
    """Require exactly two visible, authenticated, non-electric SVG strokes.

    A text label, a marker circle or a nonphysical metadata claim alone is
    never sufficient. Match the ORIGINAL RECON source vectors at 1-um
    resolution; do not infer a new Circuit.Net or physical conductor.
    """
    regions = root.findall(
        f".//{SVG}g[@data-layer='typed-nonphysical-continuations']"
    )
    demand(len(regions) == 1,
           "QA_C13_B_STUB_LAYER_MISSING_OR_DUPLICATE")
    region = regions[0]
    strokes = region.findall(f"./{SVG}line")
    expected = b_witness.get("source_b_stubs_um")
    demand(isinstance(expected, dict) and set(expected) ==
           {"X2.1", "R5.2"},
           "QA_C13_SIGNED_B_TWO_STUB_SOURCE_WITNESS_NOT_PRESENT")
    markers = {"b-X2": "X2.1", "b-R5": "R5.2"}
    anchors = b_witness.get("source_b_marker_um")
    demand(isinstance(anchors, dict) and set(anchors) == set(markers),
           "QA_C13_SIGNED_B_MARKER_INVENTORY_CHANGED")
    for name, reference in markers.items():
        stub = expected[reference]
        demand(isinstance(stub, dict) and
               set(stub) == {"start", "end"} and
               stub["end"] == anchors[name] and
               all(isinstance(p, list) and len(p) == 2 and
                   all(type(n) is int for n in p)
                   for p in stub.values()) and
               stub["start"] != stub["end"] and
               (stub["start"][0] == stub["end"][0] or
                stub["start"][1] == stub["end"][1]),
               "QA_C13_SIGNED_B_SOURCE_STUB_VECTOR_NOT_AUTHENTIC")
    demand(len(strokes) == 2 and
           {line.get("data-nonphysical-net-continuation")
            for line in strokes} == set(markers),
           "QA_C13_NATIVE_B_STUB_MISSING_DUPLICATED_OR_ANONYMOUS")
    ids = set()
    for line in strokes:
        name = line.get("data-nonphysical-net-continuation")
        reference = markers[name]
        stub = expected[reference]
        actual = (
            (Decimal(line.get("x1")) * 1000,
             Decimal(line.get("y1")) * 1000),
            (Decimal(line.get("x2")) * 1000,
             Decimal(line.get("y2")) * 1000),
        )
        stub_id = line.get("data-source-stub-id")
        demand(stub_id is not None and stub_id != "" and
               stub_id not in ids,
               "QA_C13_B_STUB_SOURCE_ID_MISSING_OR_DUPLICATED")
        ids.add(stub_id)
        demand(actual == (tuple(stub["start"]), tuple(stub["end"])) and
               line.get("data-source-pin-ref") == reference and
               line.get("data-layer") == "nonphysical-continuation-stub" and
               line.get("data-nonphysical") == "true" and
               line.get("data-electrical-junction") == "false" and
               line.get("data-connectable") == "false" and
               line.get("stroke") == "#000000" and
               line.get("stroke-width") == "0.3" and
               line.get("fill") == "none",
               "QA_C13_B_STUB_1UM_GEOMETRY_STYLE_OR_ELECTRICITY_FORGERY")
    demand(not region.findall(f"./{SVG}path") and
           not region.findall(f"./{SVG}polyline"),
           "QA_C13_B_STUB_HIDDEN_ALTERNATIVE_PATH")
    return "PASS_TWO_SOURCE_SIGNED_NONPHYSICAL_STROKES"


def adversarial_b_native_svg(
    source_dir: Path, b_anchor: dict, font_sha: str, b_witness: dict,
) -> dict:
    """Hostile mutations of actual PAINT XML only, never a surrogate sheet."""
    from copy import deepcopy

    authentic = (source_dir /
                 "TL494_COMPACT_A3_NEW_ROUTE_BLOCKED_diagnostic.svg").read_bytes()

    def layer(root: ET.Element) -> ET.Element:
        candidate = root.find(
            f".//{SVG}g[@data-layer='typed-nonphysical-continuations']"
        )
        demand(candidate is not None, "QA_C13_B_NEGATIVE_NO_GENUINE_LAYER")
        return candidate

    def circle(g: ET.Element) -> ET.Element:
        return g.findall(f"./{SVG}circle")[0]

    def label(g: ET.Element) -> ET.Element:
        return g.findall(f"./{SVG}text")[0]

    def editor(g: ET.Element) -> ET.Element:
        return g.findall(f"./{SVG}rect")[0]

    def stroke(g: ET.Element) -> ET.Element:
        return g.findall(f"./{SVG}line")[0]

    def without_strokes(g: ET.Element) -> None:
        for line in list(g.findall(f"./{SVG}line")):
            g.remove(line)

    def swap_endpoints(g: ET.Element) -> None:
        line = stroke(g)
        x1, y1 = line.get("x1"), line.get("y1")
        line.set("x1", line.get("x2"))
        line.set("y1", line.get("y2"))
        line.set("x2", x1)
        line.set("y2", y1)

    cases = {
        "one_um_marker_x_shift": lambda g: circle(g).set(
            "cx", str(Decimal(circle(g).get("cx")) + Decimal("0.001"))
        ),
        "foreign_nonphysical_b_id": lambda g: circle(g).set(
            "data-nonphysical-net-continuation", "a-X2"
        ),
        "fake_electrical_connection_dot": lambda g: circle(g).set(
            "data-electrical-junction", "true"
        ),
        "copied_b_end_id": lambda g: circle(g).set(
            "data-nonphysical-net-continuation", "b-R5"
        ),
        "forged_a_label": lambda g: setattr(label(g), "text", "a"),
        "wrong_TypeA_font_sha": lambda g: label(g).set(
            "data-font-sha256", "0" * 64
        ),
        "wrong_TypeA_family": lambda g: label(g).set(
            "font-family", "OpenGost Type A TT"
        ),
        "faked_active_green_continuation_pad": lambda g: editor(g).set(
            "data-connectable", "true"
        ),
        "removed_nonphysical_source_policy": lambda g: g.set(
            "data-do-not-infer-net-from-shapes", "false"
        ),
        "missing_b_X2_stub_line": lambda g: g.remove(stroke(g)),
        "missing_both_stub_lines": without_strokes,
        "duplicated_b_X2_stub_line": lambda g: g.append(
            deepcopy(stroke(g))
        ),
        "false_source_pinref": lambda g: stroke(g).set(
            "data-source-pin-ref", "X2.2"
        ),
        "false_continuation_id": lambda g: stroke(g).set(
            "data-nonphysical-net-continuation", "a-X2"
        ),
        "one_um_stub_start_shift": lambda g: stroke(g).set(
            "x1", str(Decimal(stroke(g).get("x1")) + Decimal("0.001"))
        ),
        "one_um_stub_end_shift": lambda g: stroke(g).set(
            "y2", str(Decimal(stroke(g).get("y2")) + Decimal("0.001"))
        ),
        "reversed_stub_vector": swap_endpoints,
        "forged_electrical_stub": lambda g: stroke(g).set(
            "data-connectable", "true"
        ),
        "forged_junction_stub": lambda g: stroke(g).set(
            "data-electrical-junction", "true"
        ),
        "wired_layer_stub": lambda g: stroke(g).set(
            "data-layer", "wires"
        ),
        "invisible_stub": lambda g: stroke(g).set(
            "stroke", "#ffffff"
        ),
        "thin_stub_ink": lambda g: stroke(g).set(
            "stroke-width", "0.2"
        ),
        "duplicated_source_stub_id": lambda g: g.findall(
            f"./{SVG}line"
        )[1].set("data-source-stub-id", stroke(g).get("data-source-stub-id")),
        "anonymous_extra_line": lambda g: ET.SubElement(
            g, SVG + "line", {"x1": "0", "y1": "0",
                             "x2": "1", "y2": "0"}
        ),
    }
    genuine = ET.fromstring(authentic)
    validate_real_b_native_layer(
        genuine, b_anchor, font_sha, "diagnostic",
    )
    demand(assess_source_b_stub_ink(genuine, b_witness) ==
           "PASS_TWO_SOURCE_SIGNED_NONPHYSICAL_STROKES",
           "QA_C13_NOT_A_POSITIVE_REAL_OWNER_B_STROKE_FIXTURE")
    rejected = {}
    for key, mutate in cases.items():
        root = ET.fromstring(authentic)
        mutate(layer(root))
        try:
            validate_real_b_native_layer(
                root, b_anchor, font_sha, "diagnostic",
            )
            assess_source_b_stub_ink(root, b_witness)
        except AssertionError:
            rejected[key] = "REJECTED_GENUINE_NATIVE_B_SOURCE"
        else:
            raise AssertionError("QA_C13_B_SVG_NEGATIVE_BYPASS:" + key)
    demand(len(rejected) == len(cases) == 24,
           "QA_C13_B_NOT_ALL_24_SVG_NEGATIVES_RUN")
    return rejected


def inspect_native(
    source_dir: Path, destination: Path, source_b_witness: Path,
) -> dict:
    # Independent signed RECON source witness; not inferred from PAINT labels.
    b_witness = json.loads(source_b_witness.read_text(encoding="utf-8"))
    demand(b_witness.get("schema") ==
           "C11_SOURCE_LOCKED_SIGNED_DA1_B_CONTINUATION_V1"
           and b_witness.get("immutable_original_commit") == ORIGINAL
           and b_witness.get("GOST_A_font_SHA256") ==
           "f77d96f832b7c902d42fc391fddf15b622c1eadeb263dd31b926888d72e0773a"
           and b_witness.get("signed_source_Circuit_Nets_identical") is True
           and b_witness.get("manufacturer_DA1_physical_pin_count") == 16
           and b_witness.get("b_marker_continuations_are_NOT_new_physical_Nets")
           is True and b_witness.get("source_b_nonphysical_Net") ==
           "b_NEGATIVE_OUTPUT" and
           set(b_witness.get("source_b_physical_members", ())) ==
           {"FU1.2", "X2.1", "R5.2"},
           "QA_C13_NATIVE_NO_REAL_SOURCE_SIGNED_B_WITNESS")
    b_anchor = b_witness["source_b_marker_um"]
    demand(set(b_anchor) == {"b-X2", "b-R5"} and
           all(type(v) is list and len(v) == 2 and
               all(type(n) is int for n in v)
               for v in b_anchor.values()),
           "QA_C13_B_WITNESS_NOT_TWO_PHYSICAL_SOURCE_VECTORS")
    signed_raw_nets = b_witness.get("true_original_nets")
    demand(isinstance(signed_raw_nets, dict) and
           len(signed_raw_nets) == 15 and
           all(isinstance(members, list) for members
               in signed_raw_nets.values()) and
           sum(len(v) for v in signed_raw_nets.values()) == 62 and
           len({p for members in signed_raw_nets.values()
                for p in members}) == 62,
           "QA_C13_B_SIGNED_SOURCE_NETS_NOT_15_UNIQUE_62")
    # Alias inversion is explicit and fully reversible. The PAINT model is
    # V5 canonical; RECON witness is original photographed naming.
    aliases = {
        "a_INPUT_PLUS": "INPUT_POS",
        "TRANSFER": "ENERGY_TRANSFER",
        "b_NEGATIVE_OUTPUT": "OUTPUT_NEG",
    }
    demanded_net_names = {
        aliases.get(name, name): set(members)
        for name, members in signed_raw_nets.items()
    }
    demand(len(demanded_net_names) == 15 and
           set(aliases) <= set(signed_raw_nets),
           "QA_C13_B_SOURCE_NET_ALIAS_FORGED")
    contacts = b_witness.get("signed_DA1_pin_contacts")
    real_owner_pin_nets = {
        member: net for net, members in signed_raw_nets.items()
        for member in members
    }
    demand(isinstance(contacts, list) and len(contacts) == 16 and
           {c.get("number") for c in contacts} ==
           {str(i) for i in range(1, 17)} and
           all(c.get("owner_Net") ==
               real_owner_pin_nets.get("DA1." + c["number"])
               for c in contacts),
           "QA_C13_B_MANUFACTURER_16_PINREF_NET_NOT_SOURCE")
    manufacturer = {c["number"]: c for c in contacts}
    demand(all(manufacturer[n].get("manufacturer_name") == label and
               manufacturer[n].get("electrical_type") == "input"
               for n, label in (("3", "FEEDBACK"), ("13", "OUTPUT CTRL"))),
           "QA_C13_B_REAL_MANUFACTURER_FB_OUTPUT_CTRL_NOT_INPUT")
    manifest = json.loads(
        (source_dir / "TL494_COMPACT_A3_NEW_ROUTER_DRC_MANIFEST.json")
        .read_text(encoding="utf-8")
    )
    require = manifest
    demand(
        (require.get("model_source"),
         require.get("source_components"),
         require.get("source_nets"),
         require.get("source_net_pinrefs"),
         require.get("manufacturer_DA1_physical_pin_count"))
        == (ORIGINAL, 23, 15, 62, 16),
        "QA_C11_NATIVE_REAL_SOURCE_23_15_62_16_MISMATCH",
    )
    source = require.get("source_reference")
    demand(isinstance(source, dict) and
           source.get("components") == 23 and
           len(source.get("BOM", {})) == 23 and
           len(source.get("nets", {})) == 15 and
           sum(len(refs) for refs in source["nets"].values()) == 62,
           "QA_C11_NATIVE_ORIGINAL_BOM_AND_PHYSICAL_NETS_MISSING")
    actual_v5_nets = source["nets"]
    demand(set(actual_v5_nets) == set(demanded_net_names) and
           all(isinstance(members, list) and
               set(members) == demanded_net_names.get(name) and
               len(members) == len(demanded_net_names[name])
               for name, members in actual_v5_nets.items()),
           "QA_C13_PAINT_V5_NET_MEMBER_DRIFT_FROM_SIGNED_SOURCE")
    real_net_by_pin = {}
    for net_name, pins in source["nets"].items():
        for pin in pins:
            demand(pin not in real_net_by_pin,
                   "QA_C11_NATIVE_DUPLICATE_PHYSICAL_PINREF")
            real_net_by_pin[pin] = net_name
    demand({f"DA1.{number}" for number in range(1, 17)} <=
           set(real_net_by_pin),
           "QA_C11_NATIVE_TL494_PIN_NOT_IN_SOURCE_NET")
    route = require.get("router_attempt")
    demand(isinstance(route, dict) and
           len(route.get("net_trees", ())) == 15,
           "QA_C11_NATIVE_MISSING_REAL_15_NET_TREE_EVIDENCE")
    completed = sum(tree.get("complete") is True
                    for tree in route["net_trees"])
    demand(completed == route.get("routed_net_count"),
           "QA_C11_NATIVE_FAKE_ROUTED_NET_COUNTER")
    demand(completed < 15 or bool(route.get("print_pass")) is True,
           "QA_C11_NATIVE_FULL_15_WITHOUT_ROUTE_DRC")
    demand(require.get("source_photo_raster_comparison") ==
           "BLOCKED_NO_AUTHORITATIVE_RASTER",
           "QA_C11_NATIVE_FAKE_SOURCE_PHOTO_PARITY")
    demand(require.get("real_print_release") is False and
           require.get("gost_approved") is False and
           require.get("source_signed_16_pin_overlay") is True and
           isinstance(require.get("source_signed_overlay_sha256"), str) and
           len(require["source_signed_overlay_sha256"]) == 64 and
           require.get("nonphysical_b_marker_status") ==
           "VERIFIED_SOURCE_B_REBOUND",
           "QA_C13_NATIVE_RELEASE_OR_SIGNED_B_UNVERIFIED")
    owner_b = require.get("two_source_b_markers")
    demand(isinstance(owner_b, dict) and
           set(owner_b) == set(b_anchor) and
           all(
               owner_b[name].get("net") == "b_NEGATIVE_OUTPUT" and
               owner_b[name].get("printed_label") == "b" and
               [owner_b[name].get("x_um"), owner_b[name].get("y_um")]
               == b_anchor[name]
               for name in b_anchor
           ),
           "QA_C13_NATIVE_SOURCE_B_MARKER_OR_NET_COORDINATES_DRIFT")
    demand(set(require.get("original_named_nets_verified", ())) ==
           set(b_witness.get("true_original_nets", {})) and
           len(require.get("original_named_nets_verified", ())) == 15,
           "QA_C13_NATIVE_SOURCE_A_B_TRANSFER_NETS_RENAMED")
    demand(require.get("original_net_memberships_unchanged") is True and
           require.get("source_graph_mutated") is False,
           "QA_C11_NATIVE_INPUT_TOPOLOGY_MODIFIED")
    drc = require.get("native_post_render_route_drc")
    demand(isinstance(drc, dict) and
           drc.get("checked_symbol_geometry") is True and
           drc.get("checked_measured_text") is True,
           "QA_C11_NATIVE_POST_RENDER_DRC_MISSING_INK")
    findings = drc.get("findings")
    demand(isinstance(findings, list) and
           drc.get("error_count") ==
           sum(x.get("severity") == "error" for x in findings),
           "QA_C11_NATIVE_DRC_COUNT_FORGED")
    if completed != 15:
        demand("ROUTER_INCOMPLETE_OR_UNVERIFIED_15_NETS"
               in require.get("blockers", ()),
               "QA_C11_NATIVE_PARTIAL_GRAPH_FAKED_PRINT_PASS")
        demand(require.get("printable_candidate") is False,
               "QA_C11_NATIVE_PARTIAL_PRINT_ACCEPTED")
    actual_segments = require.get("route_segments")
    demand(type(actual_segments) is int and actual_segments >= 0 and
           route.get("graph_segments") == actual_segments,
           "QA_C11_NATIVE_GRAPH_SEGMENT_COUNT_FORGED")
    destination.mkdir(parents=True, exist_ok=True)
    modes = {}
    views = []
    for name in ("clean", "diagnostic"):
        target = source_dir / f"TL494_COMPACT_A3_NEW_ROUTE_BLOCKED_{name}.svg"
        svg = target.read_bytes()
        root = ET.fromstring(svg)
        demand(root.tag == SVG + "svg" and
               root.get("data-release") ==
               "BLOCKED_INCOMPLETE_OR_PRINT_DRC",
               "QA_C11_NATIVE_SVG_NOT_BLOCKED")
        demand(root.get("data-route-graph-sha256") ==
               require.get("graph_sha256") and
               root.get("data-render-route-kind") ==
               "EXTERNAL_VERIFIED_MODEL_GRAPH",
               "QA_C11_NATIVE_NOT_GENUINE_VERIFIED_GRAPH_RENDER")
        demand(root.get("data-source-components") == "23" and
               root.get("data-source-nets") == "15" and
               root.get("data-actual-route-segments") == str(actual_segments),
               "QA_C11_NATIVE_SVG_LOST_SOURCE_ATTESTATION")
        demand(root.get("data-e3-normative-approval") ==
               "DRAFT_NOT_APPROVED",
               "QA_C11_NATIVE_CLAIMED_UNREVIEWED_UGO_CERTIFICATION")
        symbols = root.findall(f"./{SVG}g[@data-layer='symbols']")
        wires = root.findall(f".//{SVG}line[@data-layer='wires']")
        leads = root.findall(
            f".//{SVG}g[@data-layer='ic-physical-pin-leads']/{SVG}line"
        )
        targets = root.findall(
            f".//{SVG}g[@data-layer='editor-connection-targets']/{SVG}rect"
        )
        demand(len(symbols) == 23 and len(wires) == actual_segments
               and len(leads) == 16,
               "QA_C11_NATIVE_SVG_LOST_23_16_OR_WIRES")
        demand({lead.get("data-pin-number") for lead in leads} ==
               {str(n) for n in range(1, 17)},
               "QA_C11_NATIVE_WRONG_DA1_PHYSICAL_NUMBER")
        validate_real_b_native_layer(
            root, b_anchor, b_witness["GOST_A_font_SHA256"], name,
        )
        native_b_stub_status = assess_source_b_stub_ink(root, b_witness)
        demand(len(targets) == (0 if name == "clean" else 16),
               "QA_C11_NATIVE_EDITOR_LAYER_POLICY")
        tips = {}
        for lead in leads:
            number = lead.get("data-pin-number")
            demand(number not in tips,
                   "QA_C11_NATIVE_DUPLICATE_MANUFACTURER_PIN_NUMBER")
            x, y = lead.get("x2"), lead.get("y2")
            demand(x is not None and y is not None,
                   "QA_C11_NATIVE_UNRESOLVED_PHYSICAL_PIN_POINT")
            tips[number] = (round(float(x) * 1000), round(float(y) * 1000))
        if name == "diagnostic":
            demand({t.get("data-pin-ref") for t in targets} ==
                   {f"DA1.{n}" for n in range(1, 17)},
                   "QA_C11_NATIVE_DIAGNOSTIC_PHYSICAL_PINREFS_CHANGED")
            for marker in targets:
                number = marker.get("data-pin-number")
                demand(number in tips and marker.get("data-pin-ref") ==
                       f"DA1.{number}" and
                       marker.get("data-net-id") ==
                       real_net_by_pin[f"DA1.{number}"] and
                       marker.get("data-connectable") == "true" and
                       marker.get("fill") == "#148645",
                       "QA_C11_NATIVE_FOREIGN_PINREF_NET_OR_GREEN_ROLE")
                ax, ay = tips[number]
                demand((
                    marker.get("data-external-anchor-x-um"),
                    marker.get("data-external-anchor-y-um"),
                ) == (str(ax), str(ay)),
                       "QA_C11_NATIVE_MARKER_NOT_ON_ACTUAL_LEAD_TIP")
                w = round(float(marker.get("width", "0")) * 1000)
                h = round(float(marker.get("height", "0")) * 1000)
                x = round(float(marker.get("x", "0")) * 1000)
                y = round(float(marker.get("y", "0")) * 1000)
                demand(w == h == 700 and
                       2*x + w == 2*ax and 2*y + h == 2*ay,
                       "QA_C11_NATIVE_HOTSPOT_NOT_TRUE_700UM_SQUARE")
        width, height = root.get("width", ""), root.get("height", "")
        demand(width.endswith("mm") and height.endswith("mm"),
               "QA_C11_NATIVE_SVG_HAS_NO_MILLIMETRE_DIMENSIONS")
        mm = (float(width[:-2]), float(height[:-2]))
        demand(all(0 < dimension < 1200 for dimension in mm),
               "QA_C11_NATIVE_INVALID_PHYSICAL_SCALE")
        destination_png = destination / (target.stem + "-300dpi.png")
        # SVG original source remains byte-for-byte unchanged on disk.
        cairosvg.svg2png(
            bytestring=svg, write_to=str(destination_png), dpi=300,
        )
        with Image.open(destination_png) as raster:
            demand(raster.format == "PNG", "QA_C11_NATIVE_NOT_REAL_PNG")
